#!/bin/bash
# RCTD 主脚本扫盘 - 看 SUBSAMPLE/主循环/OUT_DIR/reference 加载
# 用法: bash scan_rctd_script.sh > scan_rctd_script.txt 2>&1

PR="/mnt/BioDisk/wangmingyuan/SGS10_analysis"
SCRIPT="$PR/scripts/rctd_batch_10samples.R"

echo "==============================================================================="
echo "RCTD 主脚本扫盘"
echo "==============================================================================="

if [ ! -f "$SCRIPT" ]; then
    echo "ERROR: 脚本不存在: $SCRIPT"
    exit 1
fi

echo "总行数: $(wc -l < $SCRIPT)"

# ---------- 1. 顶部 config (line 1-100) ----------
echo ""
echo "===== 1. 顶部 config (line 1-100) ====="
echo "-------------------------------------------------------------------------------"
sed -n '1,100p' "$SCRIPT"

# ---------- 2. SUBSAMPLE + reference (line 100-260) ----------
echo ""
echo "===== 2. SUBSAMPLE 配置 + reference 加载 (line 100-260) ====="
echo "-------------------------------------------------------------------------------"
sed -n '100,260p' "$SCRIPT"

# ---------- 3. run_rctd_on_sample (line 286-410) ----------
echo ""
echo "===== 3. run_rctd_on_sample (line 286-410) ====="
echo "-------------------------------------------------------------------------------"
sed -n '286,410p' "$SCRIPT"

# ---------- 4. 主循环 (line 410-end) ----------
echo ""
echo "===== 4. 主循环 + 后处理 (line 410-end) ====="
echo "-------------------------------------------------------------------------------"
sed -n '410,$p' "$SCRIPT"

echo ""
echo "==============================================================================="
echo "完成"
echo "==============================================================================="x
